package io.github.cyonecoder.salatapi.secapproach;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import io.github.cyonecoder.salatapi.city.MoroccoCityRegistry;
import io.github.cyonecoder.salatapi.common.model.Prayer;
import io.github.cyonecoder.salatapi.secapproach.calculation.HabousRawEngine;
import io.github.cyonecoder.salatapi.secapproach.configuration.ReconstructedMethod;
import io.github.cyonecoder.salatapi.secapproach.configuration.SecApproachParameters;
import io.github.cyonecoder.salatapi.secapproach.exception.CityNotSupportedException;
import io.github.cyonecoder.salatapi.secapproach.service.SecApproachCalculator;
import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/**
 * Proves the ported sec-approach engine reproduces the research branch exactly.
 *
 * <p>The fixture {@code golden-vectors-v2.csv} was generated by running the
 * <em>original</em> {@code SecondsApproachPrayerTimesProvider} from source commit
 * {@code 01ee8d4} over all 48 trained cities across 11 dates spanning solstices,
 * equinoxes, month and year boundaries, a leap day, and both edges of the
 * training window (2026-06-17 .. 2026-07-16).
 *
 * <p>This is the guard the whole extraction rests on. The offsets encode ~97%
 * exact agreement with the official Habous timetable; that agreement lives in the
 * interaction between the solar series, the raw-seconds rounding and the floor to
 * the minute. A port that is merely "equivalent-looking" can shift a boundary
 * case by one minute and silently lose it. Every vector must match to the minute
 * — there is no tolerance here by design.
 */
class SecApproachEngineParityTest {

    private static final String GOLDEN = "/fixtures/secapproach/golden-vectors-v2.csv";

    private record Vector(String city, LocalDate date, Prayer prayer, LocalTime expected) {}

    private static SecApproachCalculator calculator;
    private static List<Vector> vectors;

    @BeforeAll
    static void setUp() {
        calculator = new SecApproachCalculator(
                new MoroccoCityRegistry(),
                new HabousRawEngine(),
                ReconstructedMethod.frozen(),
                new SecApproachParameters());
        vectors = loadVectors();
    }

    @Test
    void everyGoldenVectorIsReproducedExactly() {
        // Compute one schedule per city/date, then check all six prayers against it.
        Map<String, LocalTime> actual = new LinkedHashMap<>();
        Map<String, List<Vector>> byCityDate = new LinkedHashMap<>();
        for (Vector v : vectors) {
            byCityDate.computeIfAbsent(v.city() + "|" + v.date(), k -> new ArrayList<>()).add(v);
        }
        byCityDate.forEach((key, group) -> {
            Vector first = group.get(0);
            var times = calculator.computeTimes(first.city(), first.date());
            for (Vector v : group) {
                actual.put(v.city() + "|" + v.date() + "|" + v.prayer(), times.get(v.prayer()));
            }
        });

        List<String> mismatches = new ArrayList<>();
        for (Vector v : vectors) {
            LocalTime got = actual.get(v.city() + "|" + v.date() + "|" + v.prayer());
            if (!v.expected().equals(got)) {
                mismatches.add(v.city() + " " + v.date() + " " + v.prayer()
                        + ": expected " + v.expected() + " but ported engine gave " + got);
            }
        }

        assertThat(mismatches).as("ported engine must match the research branch exactly").isEmpty();
        assertThat(vectors).hasSize(3168);
    }

    @Test
    void theFixtureCoversAll48CitiesAndAllSixPrayers() {
        assertThat(vectors.stream().map(Vector::city).distinct().toList()).hasSize(48);
        assertThat(vectors.stream().map(Vector::prayer).distinct().toList())
                .containsExactlyInAnyOrder(Prayer.values());
        assertThat(vectors.stream().map(Vector::date).distinct().toList()).hasSize(11);

        // Every city must be covered by the parameter set, not merely present in the fixture.
        SecApproachParameters parameters = new SecApproachParameters();
        assertThat(vectors.stream().map(Vector::city).distinct().toList())
                .allSatisfy(city -> assertThat(parameters.isSupported(city)).isTrue());
    }

    @Test
    void theReconstructedMethodIsTheFrozenReleasedFormula() {
        var candidate = ReconstructedMethod.frozen();

        // These are the released values; a resource swap must not pass silently.
        assertThat(candidate.fajrAngle()).isEqualTo(19.026);
        assertThat(candidate.ishaAngle()).isEqualTo(16.866);
        assertThat(candidate.asrShadowFactor()).isEqualTo(1.009);
        assertThat(candidate.dhuhrAdjustmentSeconds()).isEqualTo(304);
        assertThat(candidate.roundingPolicy().name()).isEqualTo("NEAREST_MINUTE");
        assertThat(candidate.operationOrder().name()).isEqualTo("RAW_THEN_ADJUST_THEN_ROUND");
        assertThat(candidate.elevationAdjustedHorizon()).isFalse();
    }

    @Test
    void anUnsupportedCityIsRefusedRatherThanCalculated() {
        // 'berkane' is mapped and has official data, but was never trained.
        assertThat(calculator.supports("berkane")).isFalse();
        assertThatThrownBy(() -> calculator.computeTimes("berkane", LocalDate.of(2026, 7, 15)))
                .isInstanceOf(CityNotSupportedException.class)
                .hasMessageContaining("No sec-approach offsets");

        assertThatThrownBy(() -> calculator.computeTimes("atlantis", LocalDate.of(2026, 7, 15)))
                .isInstanceOf(CityNotSupportedException.class)
                .hasMessageContaining("Unknown city");
    }

    @Test
    void aliasesResolveToTheSameSchedule() {
        LocalDate date = LocalDate.of(2026, 7, 15);
        assertThat(calculator.computeTimes("Casablanca", date))
                .isEqualTo(calculator.computeTimes("casablanca", date));
    }

    private static List<Vector> loadVectors() {
        List<Vector> loaded = new ArrayList<>();
        try (InputStream in = SecApproachEngineParityTest.class.getResourceAsStream(GOLDEN);
                BufferedReader reader = new BufferedReader(
                        new InputStreamReader(Objects.requireNonNull(in, "missing " + GOLDEN), StandardCharsets.UTF_8))) {
            String line = reader.readLine(); // header
            while ((line = reader.readLine()) != null) {
                if (line.isBlank()) {
                    continue;
                }
                String[] parts = line.split(",");
                loaded.add(new Vector(
                        parts[0],
                        LocalDate.parse(parts[1]),
                        Prayer.fromKey(parts[2]).orElseThrow(),
                        LocalTime.parse(parts[3])));
            }
        } catch (Exception e) {
            throw new IllegalStateException("Failed to read golden vectors", e);
        }
        return List.copyOf(loaded);
    }
}
